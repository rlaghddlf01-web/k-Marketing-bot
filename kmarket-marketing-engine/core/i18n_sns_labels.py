    if lang_clean in SNS_GUIDE_LABELS:
        return SNS_GUIDE_LABELS[lang_clean]
    # Fallback to English for unlisted codes
    return SNS_GUIDE_LABELS.get("en", SNS_GUIDE_LABELS["en"])
